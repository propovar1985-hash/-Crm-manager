-- Каталог просчётника импортирован из книги пользователя. Цены сохраняются снимком в каждой смете.
create table if not exists public.furniture_estimate_catalog (
 id uuid primary key default gen_random_uuid(), category text not null, subgroup text not null,
 item_name text not null, unit text not null default 'шт',
 source_price numeric(14,2) not null default 0 check(source_price>=0),
 supplier_name text not null default 'Прайс пользователя', is_active boolean not null default true,
 source_label text not null default 'Таблица пользователя', created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(), unique(category,subgroup,item_name)
);
create index if not exists furniture_estimate_catalog_category_idx on public.furniture_estimate_catalog(category,subgroup);
alter table public.furniture_estimate_catalog enable row level security;
drop policy if exists "authenticated manage estimate catalog" on public.furniture_estimate_catalog;
create policy "authenticated manage estimate catalog" on public.furniture_estimate_catalog for all to authenticated using(true) with check(true);
grant select,insert,update,delete on public.furniture_estimate_catalog to authenticated;
alter table public.furniture_estimate_items add column if not exists catalog_item_id uuid references public.furniture_estimate_catalog(id) on delete set null;
alter table public.furniture_estimate_lines add column if not exists catalog_item_id uuid references public.furniture_estimate_catalog(id) on delete set null;
